def default_service_payload(entry):
    payload = dict(entry)
    image = DEFAULT_SERVICE_IMAGE_BY_CATEGORY.get(payload["category"])
    if image:
        payload["image"] = image
    return payload


def seed_default_services(service_model):
    created = 0
    updated = 0

    for entry in DEFAULT_SERVICE_CATALOG:
        payload = default_service_payload(entry)
        image = payload.pop("image", None)

        service, was_created = service_model.objects.update_or_create(
            title=payload["title"],
            defaults=payload,
        )

        if was_created:
            created += 1
        else:
            updated += 1

        if image and (was_created or not service.image):
            service.image = image
            service.save(update_fields=["image"])

    return {
        "created": created,
        "updated": updated,
        "total": service_model.objects.count(),
    }
